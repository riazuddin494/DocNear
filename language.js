/* =========================================================
   CHANGE LANGUAGE
========================================================= */

function changeLanguage(lang) {

    /* Check language */

    if (
        lang !== "en" &&
        lang !== "bn"
    ) {

        lang = "en";

    }


    /* Save language */

    localStorage.setItem(
        "docnearLanguage",
        lang
    );


    /* =====================================================
       NAVBAR
    ===================================================== */

    document
        .querySelectorAll("[data-lang]")
        .forEach(function(element) {

            const key =
                element.getAttribute("data-lang");


            if (
                translations[lang] &&
                translations[lang][key]
            ) {

                element.textContent =
                    translations[lang][key];

            }

        });


    /* =====================================================
       LOGO
    ===================================================== */

    const logoTitle =
        document.querySelector(
            ".logo-text h2"
        );


    const logoSubtitle =
        document.querySelector(
            ".logo-text p"
        );


    if (logoTitle) {

        logoTitle.textContent =
            translations[lang].careNear;

    }


    if (logoSubtitle) {

        logoSubtitle.textContent =
            translations[lang].alwaysHere;

    }


    /* =====================================================
       HERO BADGE
    ===================================================== */

    const badge =
        document.querySelector(
            ".hero-left .badge"
        );


    if (badge) {

        badge.textContent =
            translations[lang].smartHealthcare;

    }


    /* =====================================================
       HERO TITLE
    ===================================================== */

    const heroTitle =
        document.querySelector(
            ".hero-left h1"
        );


    if (heroTitle) {

        heroTitle.innerHTML = `

            ${translations[lang].heroTitle}

            <br>

            ${translations[lang].heroStart}

            <span>DocNear</span>

        `;

    }


    /* =====================================================
       HERO DESCRIPTION
    ===================================================== */

    const heroDesc =
        document.querySelector(
            ".hero-left .desc"
        );


    if (heroDesc) {

        heroDesc.textContent =
            translations[lang].heroDesc;

    }


    /* =====================================================
       LEARN MORE BUTTON
    ===================================================== */

    const learnButton =
        document.querySelector(
            ".hero-buttons .primary"
        );


    if (learnButton) {

        learnButton.textContent =
            translations[lang].learnMore;

    }


    /* =====================================================
       AI HEADER
    ===================================================== */

    const aiTitle =
        document.querySelector(
            ".ai-title h3"
        );


    if (aiTitle) {

        aiTitle.textContent =
            translations[lang].aiAssistant;

    }


    const aiSubtitle =
        document.querySelector(
            ".ai-title p"
        );


    if (aiSubtitle) {

        aiSubtitle.innerHTML = `

            ${translations[lang].medicalAssistant}

            <span class="online-dot"></span>

        `;

    }


    /* =====================================================
       AI WELCOME MESSAGE
    ===================================================== */

    const firstAIMessage =
        document.querySelector(
            ".ai-chat-area .ai-message .message-content p"
        );


    if (firstAIMessage) {

        firstAIMessage.innerHTML = `

            ${translations[lang].aiWelcome}

            <br>

            ${translations[lang].aiQuestion}

        `;

    }


    /* =====================================================
       AI SUGGESTION BUTTONS
    ===================================================== */

    const suggestions =
        document.querySelectorAll(
            ".ai-suggestions button"
        );


    if (suggestions.length >= 4) {

        suggestions[0].textContent =
            translations[lang].diabetes;


        suggestions[1].textContent =
            translations[lang].cbc;


        suggestions[2].textContent =
            translations[lang].skin;


        suggestions[3].textContent =
            translations[lang].bp;

    }


    /* =====================================================
       AI INPUT
    ===================================================== */

    const aiInput =
        document.getElementById(
            "aiInput"
        );


    if (aiInput) {

        aiInput.placeholder =
            translations[lang].aiPlaceholder;

    }


    /* =====================================================
       AI DISCLAIMER
    ===================================================== */

    const disclaimer =
        document.querySelector(
            ".ai-disclaimer"
        );


    if (disclaimer) {

        disclaimer.innerHTML = `

            <i class="fa-solid fa-circle-info"></i>

            ${translations[lang].disclaimer}

        `;

    }


    /* =====================================================
       ABOUT BADGE
    ===================================================== */

    const aboutBadge =
        document.querySelector(
            ".about-badge"
        );


    if (aboutBadge) {

        aboutBadge.textContent =
            translations[lang].about;

    }


    /* =====================================================
       ABOUT TITLE
    ===================================================== */

    const aboutTitle =
        document.querySelector(
            ".about-container h2"
        );


    if (aboutTitle) {

        aboutTitle.textContent =
            translations[lang].aboutTitle;

    }


    /* =====================================================
       ABOUT DESCRIPTION
    ===================================================== */

    const aboutDescription =
        document.querySelector(
            ".about-container > p"
        );


    if (aboutDescription) {

        aboutDescription.textContent =
            translations[lang].aboutDescription;

    }


    /* =====================================================
       MISSION / VISION / WHY DOCNEAR
    ===================================================== */

    const aboutCards =
        document.querySelectorAll(
            ".about-card"
        );


    /* -----------------------------------------------
       MISSION
    ------------------------------------------------ */

    if (aboutCards.length >= 1) {

        const missionTitle =
            aboutCards[0].querySelector("h3");


        const missionText =
            aboutCards[0].querySelector("p");


        if (missionTitle) {

            missionTitle.textContent =
                translations[lang].mission;

        }


        if (missionText) {

            missionText.textContent =
                translations[lang].missionText;

        }

    }


    /* -----------------------------------------------
       VISION
    ------------------------------------------------ */

    if (aboutCards.length >= 2) {

        const visionTitle =
            aboutCards[1].querySelector("h3");


        const visionText =
            aboutCards[1].querySelector("p");


        if (visionTitle) {

            visionTitle.textContent =
                translations[lang].vision;

        }


        if (visionText) {

            visionText.textContent =
                translations[lang].visionText;

        }

    }


    /* -----------------------------------------------
       WHY DOCNEAR
    ------------------------------------------------ */

    if (aboutCards.length >= 3) {

        const whyTitle =
            aboutCards[2].querySelector("h3");


        const whyText =
            aboutCards[2].querySelector("p");


        if (whyTitle) {

            whyTitle.textContent =
                translations[lang].why;

        }


        if (whyText) {

            whyText.textContent =
                translations[lang].whyText;

        }

    }


    /* =====================================================
       LANGUAGE BUTTON ACTIVE STATE
    ===================================================== */

    const englishBtn =
        document.getElementById(
            "englishBtn"
        );


    const banglaBtn =
        document.getElementById(
            "banglaBtn"
        );


    if (englishBtn) {

        englishBtn.classList.toggle(
            "active",
            lang === "en"
        );

    }


    if (banglaBtn) {

        banglaBtn.classList.toggle(
            "active",
            lang === "bn"
        );

    }

}


/* =========================================================
   LOAD SAVED LANGUAGE
========================================================= */

document.addEventListener(
    "DOMContentLoaded",
    function() {

        const savedLanguage =
            localStorage.getItem(
                "docnearLanguage"
            );


        if (
            savedLanguage === "bn" ||
            savedLanguage === "en"
        ) {

            changeLanguage(
                savedLanguage
            );

        } else {

            changeLanguage("en");

        }

    }
);